#!/usr/bin/env node
/**
 * Choose which captured cut this build compiles.
 *
 * Writes lib/workspace/captured/active.ts, which re-exports exactly one of the
 * generated modules. Everything else imports `active`, so the cut that is not
 * selected is never imported and therefore never bundled.
 *
 * That is the whole point. Hiding internal records at runtime is not a
 * boundary: before this, `dist/client` carried peptide sequences and vendor
 * pricing for anyone who opened devtools, whatever the page chose to draw. A
 * record that was never compiled in cannot be read out of the bundle.
 *
 *   node scripts/select-audience.mjs internal   # everything (default, local)
 *   node scripts/select-audience.mjs shared     # only records the spec shares
 *   node scripts/select-audience.mjs none       # no captured programme at all
 *
 * "none" is what a shared repository ships. Captured modules hold real vault
 * prose, and a record marked shareable can still discuss sequences, vendors
 * and prices in its own body, so the safe default for anything that leaves
 * this machine is to carry no capture and regenerate it locally.
 */
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "lib/workspace/captured");

const audience = process.argv[2] ?? "internal";
if (!["internal", "shared", "none"].includes(audience))
  throw new Error(
    `Audience must be "internal", "shared" or "none", got "${audience}".`,
  );

if (audience === "none") {
  writeFileSync(
    join(dir, "active.ts"),
    `// GENERATED by scripts/select-audience.mjs. Do not edit by hand.
// Audience: NONE. No captured programme is compiled into this build.
//
// Regenerate one locally:
//   node integrations/vault/preview.mjs --root <vault> --file ... > manifest.json
//   node scripts/build-captured-program.mjs --manifest manifest.json --spec <spec>
//   node scripts/select-audience.mjs internal
import type { Program } from "../core.ts";

export const capturedProgram: Program | undefined = undefined;
`,
    "utf8",
  );
  console.log("active.ts -> none  (no captured programme in this build)");
  process.exit(0);
}

const modules = readdirSync(dir).filter(
  (f) => f.endsWith(".ts") && f !== "active.ts",
);
const shared = modules.filter((f) => f.endsWith(".shared.ts"));
const internal = modules.filter((f) => !f.endsWith(".shared.ts"));

const chosen = audience === "shared" ? shared : internal;
if (chosen.length !== 1)
  throw new Error(
    `Expected exactly one ${audience} captured module, found ${chosen.length}: ${chosen.join(", ")}`,
  );
// A shared build must have a shared cut to point at. Falling back to the full
// one would silently publish everything, so refuse instead.
if (audience === "shared" && !shared.length)
  throw new Error("No shared cut exists. Run build-captured-program.mjs first.");

const file = chosen[0].replace(/\.ts$/, "");
writeFileSync(
  join(dir, "active.ts"),
  `// GENERATED by scripts/select-audience.mjs. Do not edit by hand.
// Audience: ${audience.toUpperCase()}.
//
// Only the module named here is imported, so only its records are bundled.
// Run \`node scripts/select-audience.mjs shared\` before building anything
// that leaves this machine, then \`node scripts/check-bundle-leak.mjs\`.
export { capturedProgram } from "./${file}.ts";
`,
  "utf8",
);
console.log(`active.ts -> ${file}.ts  (audience: ${audience})`);
